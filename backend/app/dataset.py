"""Dataset versioning and Frictionless-style data packages, for reproducible research and citation."""
from __future__ import annotations

import hashlib
from datetime import datetime

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from .licenses import LICENSES
from .models import Country, Indicator, Observation

_VCACHE: dict[tuple, str] = {}

SOURCE_TO_REGISTER = {"GBD": "IHME_GBD"}  # Source.code -> licenses.LICENSES code


def indicator_version(db: Session, ind: Indicator) -> str:
    """Short content hash of an indicator's observations. Changes whenever any value changes."""
    n, last = db.execute(select(func.count(), func.max(Observation.retrieved_at))
                         .where(Observation.indicator_id == ind.id)).one()
    key = (ind.id, n, last)
    if key in _VCACHE:
        return _VCACHE[key]
    h = hashlib.sha256()
    for r in db.execute(select(Observation.country_iso3, Observation.year, Observation.sex, Observation.age_group,
                               Observation.value, Observation.low, Observation.high)
                        .where(Observation.indicator_id == ind.id)
                        .order_by(Observation.country_iso3, Observation.year, Observation.sex, Observation.age_group)):
        h.update(("|".join("" if x is None else repr(x) for x in r) + "\n").encode())
    if len(_VCACHE) > 500:
        _VCACHE.clear()
    _VCACHE[key] = v = h.hexdigest()[:12]
    return v


def restriction(source_code: str) -> dict | None:
    code = SOURCE_TO_REGISTER.get(source_code, source_code)
    return next((x for x in LICENSES if x["code"] == code), None)


def indicator_csv_rows(db: Session, ind: Indicator, sex: str | None = None, age: str | None = None):
    stmt = (select(Observation, Country).join(Country, Country.iso3 == Observation.country_iso3)
            .where(Observation.indicator_id == ind.id).order_by(Country.iso3, Observation.year))
    if sex:
        stmt = stmt.where(Observation.sex == sex)
    if age:
        stmt = stmt.where(Observation.age_group == age)
    for o, c in db.execute(stmt):
        yield [c.iso3, c.name_en, o.year, o.sex, o.age_group, o.value, o.low, o.high, o.data_quality]


CSV_HEADER = ["iso3", "country", "year", "sex", "age_group", "value", "low", "high", "data_quality"]


def datapackage(db: Session, ind: Indicator, path: str | None = None) -> dict:
    src = ind.source
    reg = restriction(src.code)
    return {
        "profile": "tabular-data-package",
        "name": ind.code,
        "title": ind.name_en,
        "version": indicator_version(db, ind),
        "created": datetime.utcnow().isoformat(timespec="seconds") + "Z",
        "description": f"{ind.name_en} ({ind.measure}, unit: {ind.unit}). Values keep their data_quality class "
                       f"(reported / estimated / modeled). Generated by Global Health Atlas.",
        "sources": [{"title": src.name, "path": src.url or "", "citation": src.citation or ""}],
        "licenses": [{"name": src.license or "unknown", "title": src.license or "Licence not recorded"}],
        "x-redistribution": reg["commercial"] if reg else "unknown",
        "x-synthetic": bool(src.is_synthetic),
        "resources": [{
            "name": ind.code, "path": path or f"{ind.code}.csv", "format": "csv", "mediatype": "text/csv", "encoding": "utf-8",
            "schema": {"fields": [
                {"name": "iso3", "type": "string", "description": "ISO 3166-1 alpha-3 country code"},
                {"name": "country", "type": "string"},
                {"name": "year", "type": "integer"},
                {"name": "sex", "type": "string", "constraints": {"enum": ["ALL", "M", "F"]}},
                {"name": "age_group", "type": "string", "description": "ALL unless the source gives age bands"},
                {"name": "value", "type": "number", "description": f"unit: {ind.unit}"},
                {"name": "low", "type": "number", "description": "lower bound of the uncertainty interval, if given"},
                {"name": "high", "type": "number", "description": "upper bound of the uncertainty interval, if given"},
                {"name": "data_quality", "type": "string", "constraints": {"enum": ["reported", "estimated", "modeled"]}},
            ]},
        }],
    }
